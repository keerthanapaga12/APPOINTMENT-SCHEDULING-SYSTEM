
-- ============================================
-- Appointment Scheduling System
-- Supabase PostgreSQL Database Schema
-- ============================================

-- 1. SERVICES TABLE
CREATE TABLE IF NOT EXISTS public.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    duration_minutes INTEGER NOT NULL DEFAULT 30
        CHECK (duration_minutes > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. USER PROFILES TABLE
-- User authentication is handled by Supabase Auth.
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'user'
        CHECK (role IN ('user', 'staff')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. AVAILABLE APPOINTMENT SLOTS
CREATE TABLE IF NOT EXISTS public.availability (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name VARCHAR(100) NOT NULL
        REFERENCES public.services(name) ON UPDATE CASCADE,
    available_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT valid_slot_time CHECK (end_time > start_time),
    CONSTRAINT unique_service_slot
        UNIQUE (service_name, available_date, start_time, end_time)
);

-- 4. APPOINTMENTS TABLE
CREATE TABLE IF NOT EXISTS public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.profiles(id) ON DELETE CASCADE,
    service_name VARCHAR(100) NOT NULL
        REFERENCES public.services(name) ON UPDATE CASCADE,
    appointment_date DATE NOT NULL,
    time TIME NOT NULL,
    availability_id BIGINT NOT NULL
        REFERENCES public.availability(id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'booked'
        CHECK (status IN ('booked', 'cancelled', 'completed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. INDEXES
CREATE INDEX IF NOT EXISTS idx_availability_date_service
    ON public.availability(service_name, available_date);

CREATE INDEX IF NOT EXISTS idx_appointments_user
    ON public.appointments(user_id);

CREATE INDEX IF NOT EXISTS idx_appointments_date
    ON public.appointments(appointment_date);

CREATE INDEX IF NOT EXISTS idx_appointments_availability
    ON public.appointments(availability_id);

-- 6. ENABLE ROW LEVEL SECURITY
ALTER TABLE public.services ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.availability ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;

-- 7. SERVICES POLICIES
-- Anyone can read active services.
CREATE POLICY "Anyone can view active services"
ON public.services
FOR SELECT
TO anon, authenticated
USING (is_active = TRUE);

-- 8. PROFILES POLICIES
-- Users can view and update their own profiles.
CREATE POLICY "Users can view their own profile"
ON public.profiles
FOR SELECT
TO authenticated
USING (auth.uid() = id);

CREATE POLICY "Users can update their own profile"
ON public.profiles
FOR UPDATE
TO authenticated
USING (auth.uid() = id)
WITH CHECK (auth.uid() = id);

-- 9. AVAILABILITY POLICIES
-- Anyone can view available appointment slots.
CREATE POLICY "Anyone can view available slots"
ON public.availability
FOR SELECT
TO anon, authenticated
USING (is_available = TRUE);

-- 10. APPOINTMENT POLICIES
-- Users can view their own appointments.
CREATE POLICY "Users can view their own appointments"
ON public.appointments
FOR SELECT
TO authenticated
USING (auth.uid() = user_id);

-- Users can create appointments for themselves.
CREATE POLICY "Users can create their own appointments"
ON public.appointments
FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = user_id);

-- Users can cancel their own appointments.
CREATE POLICY "Users can cancel their own appointments"
ON public.appointments
FOR UPDATE
TO authenticated
USING (auth.uid() = user_id)
WITH CHECK (auth.uid() = user_id);

